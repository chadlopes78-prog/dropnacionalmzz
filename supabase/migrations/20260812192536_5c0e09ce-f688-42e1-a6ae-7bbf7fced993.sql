CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = public AS $$
BEGIN NEW.updated_at = now(); RETURN NEW; END; $$;

CREATE TRIGGER products_updated_at BEFORE UPDATE ON public.products FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER orders_updated_at BEFORE UPDATE ON public.orders FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE OR REPLACE FUNCTION public.log_order_event()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.order_events(order_id, description) VALUES (NEW.id, 'Encomenda criada');
  ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO public.order_events(order_id, description)
    VALUES (NEW.id, 'Estado alterado para ' || NEW.status || COALESCE(' - ' || NEW.cancel_reason, ''));
    IF NEW.status = 'entregue' AND OLD.status <> 'entregue' THEN
      UPDATE public.products SET stock = GREATEST(stock - NEW.quantity, 0) WHERE id = NEW.product_id;
    END IF;
  END IF;
  RETURN NEW;
END; $$;

CREATE TRIGGER orders_log_insert AFTER INSERT ON public.orders FOR EACH ROW EXECUTE FUNCTION public.log_order_event();
CREATE TRIGGER orders_log_update AFTER UPDATE ON public.orders FOR EACH ROW EXECUTE FUNCTION public.log_order_event();

CREATE OR REPLACE FUNCTION public.get_order_receipt(p_id uuid)
RETURNS TABLE (
  id uuid, order_number bigint, product_name text, quantity integer,
  unit_price numeric, delivery_cost numeric, total numeric,
  customer_name text, phone text, province text, city text,
  neighborhood text, reference_point text, created_at timestamptz
)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT o.id, o.order_number, o.product_name, o.quantity, o.unit_price, o.delivery_cost,
         o.total, o.customer_name, o.phone, o.province, o.city, o.neighborhood,
         o.reference_point, o.created_at
  FROM public.orders o WHERE o.id = p_id;
$$;
GRANT EXECUTE ON FUNCTION public.get_order_receipt(uuid) TO anon, authenticated;

